"""AIMax authored local brief demo. No model calls, no network, no user files."""
from pathlib import Path
import json, hashlib, platform

ROOT = Path(__file__).resolve().parent
FIELDS = {
    'Brand': ['Name', 'Category', 'Description', 'Stage', 'Website'],
    'Audience': ['Primary Audience', 'Key Problem', 'Their Language'],
    'Positioning': ['Differentiation', 'Competitors', 'Market Position'],
    'Brand Personality': ['Personality Words', 'Tone', 'Voice Admires'],
    'Values & Mission': ['Core Values', 'Mission'],
    'Goals': ['Primary Goal', 'Key Metrics'],
}

def validate(brief):
    missing = [f'{section}.{field}' for section, fields in FIELDS.items()
               for field in fields if not brief.get(section, {}).get(field)]
    if missing:
        raise ValueError('Missing fields: ' + ', '.join(missing))

def render(brief):
    validate(brief)
    return '# Brand Context\n\n' + '\n\n'.join(
        '## ' + section + '\n' + '\n'.join(f'- **{f}**: {brief[section][f]}' for f in fields)
        for section, fields in FIELDS.items()) + '\n'

def update_tone(brief, tone, expected_digest):
    if hashlib.sha256(render(brief).encode()).hexdigest() != expected_digest:
        raise ValueError('Brief changed; read current version before updating.')
    result = json.loads(json.dumps(brief))
    result['Brand Personality']['Tone'] = tone
    return result

def main():
    brief = json.loads((ROOT / 'input.json').read_text())
    before = render(brief)
    digest = hashlib.sha256(before.encode()).hexdigest()
    after_brief = update_tone(brief, 'Calm and direct; informal without jokes.', digest)
    after = render(after_brief)
    output = ROOT / 'output'
    (output / '.agents').mkdir(parents=True, exist_ok=True)
    (output / 'before.md').write_text(before)
    (output / '.agents/brand-context.md').write_text(after)
    # Two downstream outputs authored for this demonstration, not generated by a model.
    homepage = 'Project handoffs your clients can follow.\nClient approvals and decisions, together in one shared project space.'
    email = 'Subject: Your project decisions, in one place\nBring client approvals and handoff notes into one shared project space.'
    (output / 'homepage.txt').write_text(homepage)
    (output / 'email.txt').write_text(email)
    changed = [f'{s}.{f}' for s, fs in FIELDS.items() for f in fs if brief[s][f] != after_brief[s][f]]
    assert len(FIELDS) == 6
    assert sum(map(len, FIELDS.values())) == 18
    assert changed == ['Brand Personality.Tone']
    assert (output / '.agents/brand-context.md').read_text() == after
    assert after_brief['Positioning']['Competitors'].startswith('Unknown')
    assert 'shared project space' in homepage and 'shared project space' in email
    rejected = []
    for label, section, field in [('missing-name','Brand','Name'),('missing-audience','Audience','Primary Audience'),('missing-metrics','Goals','Key Metrics')]:
        broken = json.loads(json.dumps(brief));del broken[section][field]
        try: validate(broken)
        except ValueError: rejected.append(label)
    try: update_tone(brief, 'Different', 'stale-hash')
    except ValueError: rejected.append('stale-update')
    assert len(rejected) == 4
    result = {'kind':'AIMax-authored deterministic local demonstration','fictional_brand':True,
              'python':platform.python_version(),'sections':6,'fields':18,'fields_changed':changed,
              'fields_preserved':17,'checks_passed':6,'negative_cases_rejected':rejected,
              'before_sha256':digest,'after_sha256':hashlib.sha256(after.encode()).hexdigest(),
              'limitations':['Not an independent model run','No host auto-loading tested','No business results measured','Authored copy examples are not model outputs','Validation checks presence, not truth or copy quality']}
    (ROOT / 'results.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps(result,indent=2))

if __name__ == '__main__': main()
